"""Build 1-bit, page-packed SSD1306 assets and enlarged previews."""
from pathlib import Path
import re
from PIL import Image

ROOT = Path(__file__).parent
OUT = ROOT / 'assets'
OUT.mkdir(exist_ok=True)

def pack(im):
    im = im.convert('1', dither=Image.Dither.NONE)
    return bytes(sum((1 << bit) if im.getpixel((x, page * 8 + bit)) else 0
                     for bit in range(8))
                 for page in range(im.height // 8) for x in range(im.width))

logo = Image.open(OUT / 'braxon-source.jpg').convert('L')
mask = logo.point(lambda p: 255 if p > 160 else 0)
logo = mask.crop(mask.getbbox())
logo.thumbnail((124, 26), Image.Resampling.LANCZOS)
splash = Image.new('L', (128, 32))
splash.paste(logo, ((128-logo.width)//2, (32-logo.height)//2))
splash = splash.point(lambda p: 255 if p > 100 else 0)

# Preserve the upstream 128x32 page-packed frames without resizing or redrawing.
bongo_source = (ROOT / 'third_party/qmk-bongo/bongo_cat.c').read_text()
array = bongo_source.split('animation_frames[TAP_FRAMES][ANIM_SIZE] = {', 1)[1].split('};', 1)[0]
values = bytes(int(n) for n in re.findall(r'\b\d+\b', array))
assert len(values) == 1024
cat_frames = [values[:512], values[512:]]
cats = []
for data in cat_frames:
    im = Image.new('L', (128, 32))
    for y in range(32):
        for x in range(128):
            im.putpixel((x,y), 255 if data[(y//8)*128+x] & (1 << (y%8)) else 0)
    cats.append(im)

font_source = (ROOT / 'third_party/adafruit-gfx/glcdfont.c').read_text()
font_array = font_source.split('font[] PROGMEM = {',1)[1].split('};',1)[0]
font_array = re.sub(r'//[^\n]*|/\*.*?\*/', '', font_array, flags=re.S)
columns = bytes(int(v,16) for v in re.findall(r'0x[0-9a-fA-F]{2}',font_array))
glyphs = [columns[i*5:i*5+5]+b'\0' for i in range(32,127)]
assert glyphs[ord('A')-32] != glyphs[0] and all(len(g)==6 for g in glyphs)

assets = {'knob_logo': [pack(splash)], 'knob_cat': cat_frames,
          'knob_font': glyphs}
header = ['/* Generated by generate_assets.py. Bongo frames: GPL-2.0-or-later.',
          ' * Copyright 2021 github.com/dancarroll; art credited to @pixelbenny,',
          ' * github.com/j-inc and github.com/obosob. See third_party/qmk-bongo. */',
          '#pragma once', '#include <stdint.h>']
for name, frames in assets.items():
    header.append(f'static const uint8_t {name}[{len(frames)}][{len(frames[0])}] = {{')
    for data in frames:
        header.append('    {' + ','.join(f'0x{v:02x}' for v in data) + '},')
    header.append('};')
(ROOT / 'config/boards/shields/knob_w/knob_assets.h').write_text('\n'.join(header)+'\n')
for name, im in [('logo', splash), ('idle', cats[0])]:
    im.convert('1', dither=Image.Dither.NONE).resize((768, 192), Image.Resampling.NEAREST).save(OUT / f'{name}-preview.png')
assert all(len(frame) == 512 for frame in assets['knob_logo'] + assets['knob_cat'])
assert len(set(assets['knob_cat'])) == 2
